/**
 * Returns waypoints for a letter, or generic circle if not found
 */
export function getLetterWaypoints(char) {
  const upper = (char || 'A').toUpperCase();
  return LETTER_STROKE_WAYPOINTS[upper] || LETTER_STROKE_WAYPOINTS.A;
}

/**
 * Evaluates whether a touch point is along the expected path of the letter.
 * @param {number} touchX - clientX relative to canvas
 * @param {number} touchY - clientY relative to canvas
 * @param {number} width - canvas width
 * @param {number} height - canvas height
 * @param {Array} waypoints - list of waypoints for this letter
 * @param {Set} validatedIds - set of waypoint IDs already touched
 * @param {number} tolerancePercent - radius percentage (default 15%)
 */
export function evaluateStrokeTouch(touchX, touchY, width, height, waypoints, validatedIds, tolerancePercent = 15) {
  if (!width || !height || !waypoints || waypoints.length === 0) {
    return { isOnPath: true, newlyHitId: null, distance: 0 };
  }

  const px = (touchX / width) * 100;
  const py = (touchY / height) * 100;

  let minDistance = Infinity;
  let closestWp = null;

  for (const wp of waypoints) {
    const dist = Math.hypot(px - wp.x, py - wp.y);
    if (dist < minDistance) {
      minDistance = dist;
      closestWp = wp;
    }
  }

  const isOnPath = minDistance <= tolerancePercent;
  let newlyHitId = null;

  if (isOnPath && closestWp && !validatedIds.has(closestWp.id)) {
    newlyHitId = closestWp.id;
  }

  return {
    isOnPath,
    newlyHitId,
    distance: minDistance,
    closestWaypoint: closestWp
  };
}
